#!/usr/bin/env python3
"""Split pinned SpecTec output around its handwritten builtin implementations.

The auxiliary inv_concat_ precedes the syntax types. Remove it along with the
numeric builtins, and split before s33_to_u32, the first numeric builtin. No
remaining prefix declaration may refer to a builtin, and every generated type
in a builtin signature must already be defined in the prefix. Unexpected
generator shapes and changes to the builtin inventory fail closed.
"""
from pathlib import Path
import argparse
import re

from lean_source import tokens


BUILTINS = frozenset("""
inv_concat_ s33_to_u32 truncz extend__ fabs_ fceil_ ffloor_ fnearest_
fneg_ fsqrt_ ftrunc_ iclz_ ictz_ ipopcnt_ wrap__ fadd_ fcopysign_ fdiv_
fmax_ fmin_ fmul_ fsub_ iand_ ior_ irotl_ irotr_ ishl_ ishr_ ixor_
feq_ fge_ fgt_ fle_ flt_ fne_ convert__ demote__ promote__ reinterpret__
trunc__ trunc_sat__ narrow__ ibits_ fbits_ ibytes_ fbytes_ nbytes_ vbytes_
inv_ibits_ inv_fbits_ inv_ibytes_ inv_fbytes_ inv_nbytes_ inv_vbytes_
inot_ irev_ iandnot_ ibitselect_ iavgr_ iq15mulr_sat_ fpmin_ fpmax_
lanes_ inv_lanes_
""".split())

BLOCK = re.compile(
    r"^/- Axiom Definition at: [^\n]+ -/\n"
    r"opaque (?P<name>[A-Za-z_][A-Za-z_0-9]*) (?P<sig>[^\n]+) := by\n"
    r"  first\n"
    r"     \| exact Inhabited.default\n"
    r"     \| intros ; assumption\n\n\n", re.MULTILINE)
DECL = re.compile(r"^(?:def|abbrev|inductive|structure|theorem|opaque) ([A-Za-z_][A-Za-z_0-9]*)", re.MULTILINE)
SIGNATURE = re.compile(r"(?P<binders>(?:\([^()]+\) )+): (?P<result>.+)")
BANNER = "-- Generated by scripts/spec_split.py; do not edit.\n"


def identifiers(source: str) -> set[str]:
    return {t.value for t in tokens(source) if t.kind == "ident"}


def split(source: str) -> dict[str, str]:
    blocks = list(BLOCK.finditer(source))
    names = [b["name"] for b in blocks]
    if len(names) != len(set(names)) or set(names) != BUILTINS:
        raise ValueError(f"Builtin inventory changed: missing {sorted(BUILTINS - set(names))}; "
                         f"unexpected {sorted(set(names) - BUILTINS)}; duplicates rejected")
    remainder = BLOCK.sub("", source)
    if "opaque" in identifiers(remainder):
        raise ValueError("Unrecognized opaque declaration or builtin block shape")
    boundary = next(b.start() for b in blocks if b["name"] == "s33_to_u32")
    before = [b["name"] for b in blocks if b.start() < boundary]
    if before != ["inv_concat_"]:
        raise ValueError(f"Unexpected builtins before numeric split: {before}")
    prefix = BLOCK.sub("", source[:boundary])
    suffix = BLOCK.sub("", source[boundary:])
    used = identifiers(prefix) & BUILTINS
    if used:
        raise ValueError(f"Prefix depends on builtin definitions: {sorted(used)}")
    later = set(DECL.findall(suffix))
    examples = []
    for block in blocks:
        sig = SIGNATURE.fullmatch(block["sig"])
        if sig is None:
            raise ValueError(f"Unexpected signature shape for {block['name']}")
        # Binder names can shadow generated names (e.g. `rat`); inspect types.
        types = re.findall(r"\([^():]+ : ([^()]+)\)", sig["binders"])
        mentioned = identifiers(" ".join(types) + " " + sig["result"])
        if mentioned & later:
            raise ValueError(f"Signature of {block['name']} depends on later declarations: "
                             f"{sorted(mentioned & later)}")
        examples.append(f"example : ∀ {sig['binders'].strip()}, {sig['result']} := @{block['name']}\n")
    imports = "import Wasm2Prefix\nimport SpecExt.Builtins\n\n"
    return {
        "Wasm2Prefix.lean": BANNER + prefix,
        "wasm2.0.lean": BANNER + imports + suffix,
        "Wasm2Builtins.lean": BANNER + imports + "\n".join(examples),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    try:
        outputs = split(args.input.read_text())
    except ValueError as error:
        parser.exit(1, f"spec split: {error}\n")
    args.output.mkdir(parents=True, exist_ok=True)
    for name, source in outputs.items():
        (args.output / name).write_text(source)
    print(f"Specification split: {len(BUILTINS)} builtin signatures checked")


if __name__ == "__main__":
    main()
